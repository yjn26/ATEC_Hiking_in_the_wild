#!/usr/bin/env python3
"""Generate the deterministic dynamic pebble-field include for the terrain selector."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import random


DEFAULT_SEED = 20261019
DEFAULT_COUNT = 784
LAYERS = 4
INNER_X = (-6.92, -4.08)
INNER_Y = (4.08, 6.92)
GRID_COLUMNS = 14
GRID_ROWS = 14
HORIZONTAL_AXIS = (0.055, 0.085)
VERTICAL_AXIS = (0.020, 0.030)
LAYER_Z = (0.032, 0.096, 0.160, 0.224)
BOUND_MARGIN = 1e-5


@dataclass(frozen=True)
class Pebble:
    x: float
    y: float
    z: float
    radius_x: float
    radius_y: float
    radius_z: float


def generate_pebbles(seed: int = DEFAULT_SEED, count: int = DEFAULT_COUNT) -> list[Pebble]:
    """Return a repeatable four-layer layout that begins wholly inside the basin."""
    if count != DEFAULT_COUNT:
        raise ValueError(f"count must be exactly {DEFAULT_COUNT}")

    rng = random.Random(seed)
    pebbles: list[Pebble] = []
    x_step = (INNER_X[1] - INNER_X[0]) / GRID_COLUMNS
    y_step = (INNER_Y[1] - INNER_Y[0]) / GRID_ROWS
    for layer, z in enumerate(LAYER_Z):
        for row in range(GRID_ROWS):
            for column in range(GRID_COLUMNS):
                radius_x = rng.uniform(*HORIZONTAL_AXIS)
                radius_y = rng.uniform(*HORIZONTAL_AXIS)
                radius_z = rng.uniform(*VERTICAL_AXIS)
                # Fixed cell centres keep every initial rigid ellipsoid separated.
                x = INNER_X[0] + (column + 0.5) * x_step
                y = INNER_Y[0] + (row + 0.5) * y_step
                pebbles.append(Pebble(x, y, z, radius_x, radius_y, radius_z))
    return pebbles


def render_include(pebbles: list[Pebble], seed: int) -> str:
    """Render independent translation-only bodies as direct worldbody children."""
    lines = [
        f'<mujoco model="pebble_field_seed_{seed}">',
        "  <!-- Generated by generate_pebble_terrain.py; deterministic metadata:",
        f"       seed={seed}; count={len(pebbles)}; layers={LAYERS}; inner_x={INNER_X}; inner_y={INNER_Y};",
        "       three translation-only slide joints (x/y/z), no rotation; direct worldbody body children;",
        f"       horizontal_axis={HORIZONTAL_AXIS}; vertical_axis={VERTICAL_AXIS}; layer_z={LAYER_Z};",
        "       MuJoCo native ellipsoid geoms are closed convex primitives, so OBJ meshes are unnecessary. -->",
        "  <worldbody>",
    ]
    for index, pebble in enumerate(pebbles):
        # Keep a small post-serialization margin so rounded XML limits cannot cross a basin boundary.
        x_range = (INNER_X[0] + pebble.radius_x - pebble.x + BOUND_MARGIN, INNER_X[1] - pebble.radius_x - pebble.x - BOUND_MARGIN)
        y_range = (INNER_Y[0] + pebble.radius_y - pebble.y + BOUND_MARGIN, INNER_Y[1] - pebble.radius_y - pebble.y - BOUND_MARGIN)
        z_range = (pebble.radius_z - pebble.z + BOUND_MARGIN, 0.30 - pebble.radius_z - pebble.z - BOUND_MARGIN)
        lines.extend(
            [
                f'    <body name="pebble_{index:03d}" pos="{pebble.x:.6f} {pebble.y:.6f} {pebble.z:.6f}">',
                f'      <joint name="pebble_{index:03d}_x" type="slide" axis="1 0 0" limited="true" range="{x_range[0]:.6f} {x_range[1]:.6f}" damping="1.0"/>',
                f'      <joint name="pebble_{index:03d}_y" type="slide" axis="0 1 0" limited="true" range="{y_range[0]:.6f} {y_range[1]:.6f}" damping="1.0"/>',
                f'      <joint name="pebble_{index:03d}_z" type="slide" axis="0 0 1" limited="true" range="{z_range[0]:.6f} {z_range[1]:.6f}" damping="1.5"/>',
                f'      <geom name="pebble_{index:03d}_geom" type="ellipsoid" size="{pebble.radius_x:.6f} {pebble.radius_y:.6f} {pebble.radius_z:.6f}"',
                '        material="pebble" density="850" contype="1" conaffinity="1" friction="1.30 0.03 0.001"',
                '        solref="0.004 1" solimp="0.95 0.99 0.001"/>',
                "    </body>",
            ]
        )
    lines.extend(["  </worldbody>", "</mujoco>", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--count", type=int, default=DEFAULT_COUNT)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parent / "assets" / "scene" / "generated" / "pebble_field_seed_20261019.xml",
    )
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_include(generate_pebbles(args.seed, args.count), args.seed), encoding="ascii")


if __name__ == "__main__":
    main()
